
# For Single-line Comment in Python:
# A single-line comment starts with the hash character (#) and extends to the end of the line.

# For Multi-line Comment in Python:
# Multi-line comments can be created using triple quotes (''' or """).
"""
This is a multi-line comment.
Name: Sharafat Hossain
ID: 2312599642
Department: CSE
University: ABC University
"""

# We can also use ''' to create multi-line comments.
'''
This is another multi-line comment.
It can span multiple lines.
You can write anything here.
'''